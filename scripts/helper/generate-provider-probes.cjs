const { execFileSync } = require('node:child_process');
const { readFileSync, writeFileSync } = require('node:fs');
const { join, resolve } = require('node:path');

const root = resolve(__dirname, '..', '..');
const sourcePath = join(root, 'src', 'shared', 'provider-probes.json');
const outputPath = join(
  root, 'helper', 'internal', 'providerprobe', 'registry_generated.go'
);
const providerIds = [
  'codex', 'claude', 'gemini', 'antigravity', 'opencode', 'cursor',
  'copilot', 'qwen', 'amp', 'crush', 'goose', 'aider'
];
const commandPattern = /^[A-Za-z0-9._-]{1,80}$/;

function goString(value) {
  return JSON.stringify(value)
    .replaceAll('<', '\\u003c')
    .replaceAll('>', '\\u003e')
    .replaceAll('&', '\\u0026');
}

function loadRegistry() {
  const registry = JSON.parse(readFileSync(sourcePath, 'utf8'));
  if (!Array.isArray(registry) || registry.length !== providerIds.length) {
    throw new Error('Provider probe registry has an invalid length.');
  }
  registry.forEach((probe, index) => {
    if (
      probe === null || typeof probe !== 'object' ||
      probe.provider !== providerIds[index] ||
      typeof probe.command !== 'string' || !commandPattern.test(probe.command) ||
      !Array.isArray(probe.versionArgs) || probe.versionArgs.length === 0 ||
      probe.versionArgs.length > 4 ||
      probe.versionArgs.some((arg) =>
        typeof arg !== 'string' || arg.length === 0 || arg.length > 80 ||
        /[\0\r\n]/.test(arg)
      )
    ) throw new Error(`Provider probe ${index} is invalid.`);
  });
  return registry;
}

const entries = loadRegistry().map((probe) => {
  const args = probe.versionArgs.map(goString).join(', ');
  return `\t{Provider: ${goString(probe.provider)}, Command: ${goString(probe.command)}, VersionArgs: []string{${args}}},`;
});
const generated = `// Code generated by scripts/helper/generate-provider-probes.cjs; DO NOT EDIT.\n\npackage providerprobe\n\n// Definition is one allowlisted provider version probe.\ntype Definition struct {\n\tProvider string\n\tCommand string\n\tVersionArgs []string\n}\n\nvar Registry = []Definition{\n${entries.join('\n')}\n}\n`;
writeFileSync(outputPath, generated, 'utf8');
execFileSync('gofmt', ['-w', outputPath], { stdio: 'inherit' });
